/** Translate one string. Returns it unchanged in Korean, or when untranslated. */
export function t(ko) {
  if (lang() !== 'en') return ko;
  const k = String(ko ?? '').trim();
  return EN[k] ?? ko;
}

/** Translate while preserving the leading/trailing whitespace of a text node. */
export function tNode(raw) {
  if (lang() !== 'en') return raw;
  const k = raw.trim();
  if (!k) return raw;
  const en = EN[k];
  if (en === undefined) return raw;
  const lead = raw.slice(0, raw.indexOf(k[0]));
  const tail = raw.slice(raw.lastIndexOf(k[k.length - 1]) + 1);
  return lead + en + tail;
}

/** Strings still missing a translation — used by the i18n coverage test. */
export function missing(keys) {
  return keys.filter(k => EN[k] === undefined);
}
