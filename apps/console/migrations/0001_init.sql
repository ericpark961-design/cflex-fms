-- 0001_init — the Local Console schema on PostgreSQL 16 (WO-INT-008).
-- The SQLite schema it replaces, table for table: same names, same columns,
-- same values (times epoch milliseconds in BIGINT, flags 0/1 in INTEGER, JSON
-- as TEXT), so every API answer stays what it was.
--
-- Text that a screen sorts by is COLLATE "C": byte order, as SQLite's BINARY
-- sorted it, whatever locale db01 was initialised with.
--
-- Applied once by db.js migrate() under an advisory lock and recorded in
-- schema_migrations. No extensions (no citext, no pg_partman, no pgcrypto).
--
-- Partitioned by month on ts (spec 01 §2.3, native declarative partitioning):
-- telemetry, alarm_events, audit_log — the three that grow with time. The
-- month partitions themselves are made by partitions.js (ahead of time, and
-- dropped when past retention); the DEFAULT partition takes a row no month
-- partition covers yet, so an odd timestamp is stored instead of refused.

CREATE TABLE users (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      TEXT COLLATE "C" NOT NULL,
  display_name  TEXT,
  email         TEXT,
  role          TEXT NOT NULL CHECK (role IN ('admin', 'operator', 'viewer')),
  pw_hash       TEXT NOT NULL,
  pw_changed_at BIGINT NOT NULL,
  must_change   INTEGER NOT NULL DEFAULT 1,
  disabled      INTEGER NOT NULL DEFAULT 0,
  created_at    BIGINT NOT NULL,
  last_login_at BIGINT
);
-- SQLite had COLLATE NOCASE; here the lookups and the list order use lower(username).
CREATE UNIQUE INDEX users_username_lower ON users (lower(username));

-- Append-only (spec 01 §4): the trigger refuses UPDATE and DELETE. The one
-- exception is partitions.js moving rows out of the DEFAULT partition into a
-- new month partition inside one transaction (the rows are re-inserted there
-- first); it sets cflex.partition_move for that transaction only.
-- Dropping a partition past retention is DDL and does not touch rows.
CREATE SEQUENCE audit_log_id_seq;
CREATE TABLE audit_log (
  id      BIGINT NOT NULL DEFAULT nextval('audit_log_id_seq'),
  ts      BIGINT NOT NULL,
  actor   TEXT,
  action  TEXT NOT NULL,
  target  TEXT,
  detail  TEXT,
  ip      TEXT,
  node    TEXT,
  PRIMARY KEY (id, ts)
) PARTITION BY RANGE (ts);
ALTER SEQUENCE audit_log_id_seq OWNED BY audit_log.id;
CREATE TABLE audit_log_default PARTITION OF audit_log DEFAULT;

CREATE FUNCTION audit_log_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' AND current_setting('cflex.partition_move', true) = 'on' THEN
    RETURN OLD;
  END IF;
  RAISE EXCEPTION 'audit_log is append-only';
END
$$;
CREATE TRIGGER audit_log_no_change BEFORE UPDATE OR DELETE ON audit_log
  FOR EACH ROW EXECUTE FUNCTION audit_log_append_only();

CREATE TABLE sites (
  id        TEXT COLLATE "C" PRIMARY KEY,   -- contract site code, e.g. HMA-FV
  name      TEXT NOT NULL,
  company   TEXT,
  timezone  TEXT NOT NULL DEFAULT 'America/Los_Angeles'
);

CREATE TABLE devices (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id         TEXT NOT NULL UNIQUE,   -- contract §2 sha1(tenant|site|serial)[:16]
  site_id           TEXT COLLATE "C" NOT NULL REFERENCES sites(id),
  label             TEXT COLLATE "C" NOT NULL,
  vendor            TEXT,
  model             TEXT,
  serial            TEXT,
  serial_alt        TEXT,                   -- JSON array (modular frames/modules)
  nmc_ip            TEXT,
  building          TEXT,
  floor             TEXT,
  room              TEXT,
  rack              TEXT,
  firmware          TEXT,
  mfg_date          TEXT,                   -- YYYY-MM
  battery_installed TEXT,
  battery_due       TEXT,
  in_sow            INTEGER NOT NULL DEFAULT 1,
  polling_enabled   INTEGER NOT NULL DEFAULT 1,
  thresholds        TEXT,                   -- JSON per-device override
  -- latest reading, kept on the row so the fleet list is one query
  last_ts           BIGINT,
  comm_ok           INTEGER,
  battery_pct       DOUBLE PRECISION,
  load_pct          DOUBLE PRECISION,
  temp_c            DOUBLE PRECISION,
  runtime_min       DOUBLE PRECISION,
  output_v          DOUBLE PRECISION,
  input_v           DOUBLE PRECISION,
  ups_status        TEXT,
  created_at        BIGINT NOT NULL,
  updated_at        BIGINT NOT NULL
);
CREATE INDEX idx_devices_site ON devices(site_id);

-- Raw readings: retention raw_years (default 3).
CREATE TABLE telemetry (
  device_id   TEXT NOT NULL,
  ts          BIGINT NOT NULL,
  battery_pct DOUBLE PRECISION,
  load_pct    DOUBLE PRECISION,
  temp_c      DOUBLE PRECISION,
  runtime_min DOUBLE PRECISION,
  comm_ok     INTEGER,
  m           TEXT,
  PRIMARY KEY (device_id, ts)
) PARTITION BY RANGE (ts);
CREATE TABLE telemetry_default PARTITION OF telemetry DEFAULT;

-- One row per alarm (contract alarm_id); the events are its history.
CREATE TABLE alarms (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alarm_id       TEXT NOT NULL UNIQUE,
  device_id      TEXT,
  site_id        TEXT,
  code           TEXT NOT NULL,
  severity       TEXT COLLATE "C" NOT NULL,
  title          TEXT,
  state          TEXT NOT NULL CHECK (state IN ('open', 'cleared')),
  raised_at      BIGINT NOT NULL,
  updated_at     BIGINT NOT NULL,
  cleared_at     BIGINT,
  acked_at       BIGINT,
  acked_by       TEXT,
  detail         TEXT,
  local_notified TEXT,
  maintenance    INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX idx_alarms_state ON alarms(state, severity);
CREATE INDEX idx_alarms_raised ON alarms(raised_at);

-- Alarm history: retention events_years (default 10). A partitioned table's
-- primary key must carry the partition key, so it is (event_id, ts) — a replay
-- is the same event with the same ts, and ingest.js looks the event_id up
-- (idx_alarm_events_event) under an advisory lock before it inserts.
CREATE TABLE alarm_events (
  event_id  TEXT NOT NULL,                  -- contract event_id: replays are no-ops
  alarm_id  TEXT NOT NULL,
  ts        BIGINT NOT NULL,
  kind      TEXT NOT NULL,
  title     TEXT,
  detail    TEXT,
  local_notified TEXT,                      -- what the console delivered for this event (JSON), returned again on a replay
  PRIMARY KEY (event_id, ts)
) PARTITION BY RANGE (ts);
CREATE TABLE alarm_events_default PARTITION OF alarm_events DEFAULT;
CREATE INDEX idx_alarm_events_alarm ON alarm_events(alarm_id, ts);
CREATE INDEX idx_alarm_events_event ON alarm_events(event_id);

-- alarm_id → ServiceNow incident, so a clear resolves the ticket its raise
-- opened — on either node and across restarts (notify.js).
CREATE TABLE itsm_map (
  alarm_id  TEXT PRIMARY KEY,
  value     TEXT NOT NULL,                  -- {number, sys_id, code, device_id, opened, updated?, resolved?}
  updated   BIGINT NOT NULL
);

CREATE TABLE alarm_comments (
  id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alarm_id  TEXT NOT NULL,
  ts        BIGINT NOT NULL,
  author    TEXT NOT NULL,
  kind      TEXT NOT NULL DEFAULT 'comment',  -- comment | ack | unack
  text      TEXT
);
CREATE INDEX idx_alarm_comments_alarm ON alarm_comments(alarm_id, ts);

CREATE TABLE maintenance (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id   TEXT,                         -- contract device_id; NULL with site NULL = whole node
  site_id     TEXT,
  starts_at   BIGINT NOT NULL,
  ends_at     BIGINT NOT NULL,
  reason      TEXT,
  created_by  TEXT NOT NULL,
  created_at  BIGINT NOT NULL
);
CREATE INDEX idx_maintenance_ends ON maintenance(ends_at);

-- SNMP credentials: per site (device_id NULL) or per device. secret is AES-GCM sealed.
-- NULLS NOT DISTINCT: a second PUT for the same site default updates the row
-- (ON CONFLICT finds it) instead of adding another.
CREATE TABLE credentials (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id     TEXT COLLATE "C",
  device_id   TEXT COLLATE "C",
  version     TEXT NOT NULL CHECK (version IN ('1', '2c', '3')),
  username    TEXT,                         -- v3 user (not secret)
  auth_proto  TEXT,
  priv_proto  TEXT,
  secret      TEXT,                         -- sealed JSON {community|auth_key,priv_key}
  updated_by  TEXT,
  updated_at  BIGINT NOT NULL,
  UNIQUE NULLS NOT DISTINCT (site_id, device_id)
);

-- Key/value settings: thresholds, notify channels (secrets sealed), portal status.
CREATE TABLE settings (
  key         TEXT PRIMARY KEY,
  value       TEXT NOT NULL,
  updated_by  TEXT,
  updated_at  BIGINT NOT NULL
);

CREATE TABLE collectors (
  node_id     TEXT COLLATE "C" PRIMARY KEY,
  key_hash    TEXT NOT NULL,
  created_at  BIGINT NOT NULL,
  last_seen   BIGINT,
  heartbeat   TEXT
);
